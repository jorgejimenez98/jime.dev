import type { Metadata } from "next"
import { type AppLocale, routing } from "@/i18n/routing"
import { env } from "@/lib/constants/env.constants"
import { UI } from "@/lib/constants/ui.constants"

// Ported from Crealix (src/lib/helpers/seo.helpers.ts): the one source of
// canonical URLs and hreflang, shared by page metadata and the sitemap.

export const SITE_URL = env.NEXT_PUBLIC_FRONTEND_URL.replace(/\/+$/, "")
// George in English, Jorge in Spanish: the same person, named per locale
export const SITE_NAMES = {
  en: "George Jimenez",
  es: "Jorge Jimenez"
} as const satisfies Record<AppLocale, string>

export const OPEN_GRAPH_LOCALES = {
  en: "en_US",
  es: "es_ES"
} as const satisfies Record<AppLocale, string>

// "/blog" → "/blog" (en) or "/es/blog" (es); "/" → "/" or "/es"
export function localizedPath(path: string, locale: AppLocale) {
  if (locale === routing.defaultLocale) return path
  return path === "/" ? `/${locale}` : `/${locale}${path}`
}

export function localizedUrl(path: string, locale: AppLocale) {
  return `${SITE_URL}${localizedPath(path, locale)}`
}

// Every locale plus x-default (the unprefixed English URL)
export function languagesFor(path: string): Record<string, string> {
  return {
    ...Object.fromEntries(
      routing.locales.map(locale => [locale, localizedUrl(path, locale)])
    ),
    "x-default": localizedUrl(path, routing.defaultLocale)
  }
}

export function alternatesFor(
  path: string,
  locale: AppLocale
): NonNullable<Metadata["alternates"]> {
  return {
    canonical: localizedUrl(path, locale),
    languages: languagesFor(path),
    types: { "application/rss+xml": localizedUrl(UI.ROUTES.FEED, locale) }
  }
}

// The site-wide social card, generated by [locale]/opengraph-image.tsx
export function siteOpenGraphImageUrl(locale: AppLocale) {
  return `${SITE_URL}/${locale}/opengraph-image`
}

/**
 * Open Graph fields every page shares. A page that sets its own `openGraph`
 * replaces the layout's object entirely, so it must spread these back in.
 */
export function baseOpenGraph(
  locale: AppLocale
): NonNullable<Metadata["openGraph"]> {
  return {
    siteName: SITE_NAMES[locale],
    locale: OPEN_GRAPH_LOCALES[locale],
    alternateLocale: routing.locales
      .filter(other => other !== locale)
      .map(other => OPEN_GRAPH_LOCALES[other])
  }
}
